import data from '~/data/catalog.json';

export interface Tool {
  name: string;
  categories: string[];
  primary: string;
  description: string;
  exe: string;
  run_cmd: string;
  args_hint: string;
  launch: 'stream' | 'gui' | 'web' | 'dataset';
  install: 'scoop' | 'pipx';
  package: string;
  bucket: string | null;
  note: string | null;
  verify: { args: string; contains: string } | null;
  url: string | null;
}
export interface Category { id: string; label: string; blurb: string; tools: string[] }
export interface Catalog {
  version: string;
  slots: number;
  hashFormats: number;
  buckets: string[];
  counts: Record<string, number>;
  categories: Category[];
  tools: Tool[];
}

/** tools.yaml as the site sees it (generated by scripts/sync.mjs). */
export const useCatalog = () => data as Catalog;

export const REPO = 'https://github.com/tahabenissa/winsploit';

/** A path under the site's base (for plain <a> to static files like the demo). */
export function withBase(path: string) {
  const base = useRuntimeConfig().app.baseURL || '/';
  return base.replace(/\/$/, '') + '/' + path.replace(/^\//, '');
}
